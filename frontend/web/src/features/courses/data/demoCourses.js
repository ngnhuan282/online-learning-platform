export const formatPrice = value => `${new Intl.NumberFormat('vi-VN').format(value)}đ`;
export const normalizeSearch = value =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .toLowerCase();
